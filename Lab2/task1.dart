// Task 1: Declare variables of different data types and print their values.
void main() {
  int a = 5;
  double b = 3.14;
  String name = "Alice";
  bool isStudent = true;
  print("Integer: $a");
  print("Double: $b");
  print("String: $name");
  print("Boolean: $isStudent");

  var c = 10;
  var d = 3.14;
  var name2 = "Bob";
  var isTeacher = false;
  print("$c, ${c.runtimeType}");
  print("$d, ${d.runtimeType}");
  print("$name2, ${name2.runtimeType}");
  print("$isTeacher, ${isTeacher.runtimeType}");
}
